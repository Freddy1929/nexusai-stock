WITH meses AS (
    SELECT mes, venta_mes
    FROM generate_series(0, 5) AS mes_series(mes)
    CROSS JOIN generate_series(1, 3) AS venta_series(venta_mes)
),
ventas_demo AS (
    SELECT
        (1 + mes * 3 + venta_mes)::BIGINT AS id,
        ((mes + venta_mes - 1) % 5 + 1)::BIGINT AS cliente_id,
        (date_trunc('month', CURRENT_DATE) - make_interval(months => mes)
            + make_interval(days => 4 + venta_mes * 5, hours => 10))::TIMESTAMPTZ AS fecha,
        (1 + ((mes * 3 + venta_mes - 1) % 15))::BIGINT AS producto_id,
        (1 + (venta_mes % 3))::NUMERIC(12, 2) AS cantidad
    FROM meses
),
totales AS (
    SELECT
        demo.*,
        ROUND(demo.cantidad * producto.precio_venta, 2) AS subtotal
    FROM ventas_demo AS demo
    JOIN productos AS producto ON producto.id = demo.producto_id
)
INSERT INTO ventas (id, cliente_id, fecha, subtotal, iva, total, estado)
SELECT
    id,
    cliente_id,
    fecha,
    subtotal,
    ROUND(subtotal * 0.15, 2),
    subtotal + ROUND(subtotal * 0.15, 2),
    'pagada'
FROM totales
ON CONFLICT DO NOTHING;

