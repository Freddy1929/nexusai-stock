CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('admin', 'vendedor')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    ruc VARCHAR(13) UNIQUE CHECK (ruc IS NULL OR ruc ~ '^[0-9]{13}$'),
    telefono VARCHAR(30),
    email VARCHAR(255),
    direccion TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    proveedor_id BIGINT NOT NULL REFERENCES proveedores(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    precio_compra NUMERIC(12, 2) NOT NULL CHECK (precio_compra >= 0),
    precio_venta NUMERIC(12, 2) NOT NULL CHECK (precio_venta >= 0),
    cantidad NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    unidad VARCHAR(30) NOT NULL DEFAULT 'unidad',
    limite_minimo NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (limite_minimo >= 0),
    fecha_caducidad DATE,
    imagen_url TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_identificacion VARCHAR(20) NOT NULL
        CHECK (tipo_identificacion IN ('cedula', 'ruc', 'pasaporte')),
    identificacion VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    email VARCHAR(255),
    telefono VARCHAR(30),
    direccion TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES clientes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    iva NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
    total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'pagada'
        CHECK (estado IN ('pendiente', 'pagada', 'anulada')),
    es_demo BOOLEAN NOT NULL DEFAULT FALSE,
    demo_clave VARCHAR(40),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (total = subtotal + iva)
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(id) ON UPDATE CASCADE ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    cantidad NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    CHECK (subtotal = ROUND(cantidad * precio_unitario, 2))
);

CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id BIGINT NOT NULL REFERENCES proveedores(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'recibido', 'cancelado')),
    total NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    cantidad NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
    costo_unitario NUMERIC(12, 2) NOT NULL CHECK (costo_unitario >= 0)
);

CREATE TABLE IF NOT EXISTS facturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL UNIQUE REFERENCES ventas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    numero VARCHAR(17) NOT NULL UNIQUE CHECK (numero ~ '^[0-9]{3}-[0-9]{3}-[0-9]{9}$'),
    clave_acceso VARCHAR(49) UNIQUE,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(20) NOT NULL DEFAULT 'generada'
        CHECK (estado IN ('generada', 'enviada', 'anulada', 'error')),
    pdf_url TEXT,
    email_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    email_error TEXT,
    odoo_id VARCHAR(100),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT facturas_clave_acceso_formato
        CHECK (clave_acceso IS NULL OR clave_acceso ~ '^[0-9]{49}$')
);

CREATE SEQUENCE IF NOT EXISTS facturas_numero_seq START WITH 1;

CREATE TABLE IF NOT EXISTS predicciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES productos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_calculo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    demanda_estimada NUMERIC(12, 2) NOT NULL CHECK (demanda_estimada >= 0),
    dias_restantes_stock NUMERIC(12, 2) CHECK (dias_restantes_stock IS NULL OR dias_restantes_stock >= 0),
    nivel_alerta VARCHAR(20) NOT NULL CHECK (nivel_alerta IN ('critico', 'advertencia', 'normal')),
    demanda_7_dias NUMERIC(12, 2) NOT NULL DEFAULT 0,
    demanda_15_dias NUMERIC(12, 2) NOT NULL DEFAULT 0,
    demanda_30_dias NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stock_actual NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sugerencia_reposicion NUMERIC(12, 2) NOT NULL DEFAULT 0,
    confianza VARCHAR(10) NOT NULL DEFAULT 'baja' CHECK (confianza IN ('alta', 'media', 'baja')),
    dias_con_ventas INTEGER NOT NULL DEFAULT 0,
    ventana_dias INTEGER NOT NULL DEFAULT 90
);

CREATE TABLE IF NOT EXISTS configuracion_ia (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    ventana_dias INTEGER NOT NULL CHECK (ventana_dias BETWEEN 30 AND 180),
    dias_recientes INTEGER NOT NULL CHECK (dias_recientes BETWEEN 1 AND 30),
    dias_intermedios INTEGER NOT NULL CHECK (dias_intermedios BETWEEN 8 AND 90),
    peso_reciente INTEGER NOT NULL CHECK (peso_reciente > 0),
    peso_intermedio INTEGER NOT NULL CHECK (peso_intermedio > 0),
    peso_antiguo INTEGER NOT NULL CHECK (peso_antiguo > 0),
    umbral_critico INTEGER NOT NULL CHECK (umbral_critico > 0),
    umbral_advertencia INTEGER NOT NULL CHECK (umbral_advertencia > umbral_critico),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (dias_intermedios > dias_recientes),
    CHECK (ventana_dias >= dias_intermedios)
);

